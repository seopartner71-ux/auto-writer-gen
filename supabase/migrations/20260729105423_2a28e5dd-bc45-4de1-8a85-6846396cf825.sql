## КРИТИЧНО: не печатай метаданные документа в теле
Служебные метаданные (заголовок, категория, автор, био, email, версия, CTA, целевая аудитория, источник) подставляются автоматически в обложку, футер и блок автора. Их НЕЛЬЗЯ копировать в тело статьи. Запрещены разделы «Метаданные», «О документе», «Паспорт документа», «Ссылки на клиента» и строки вида «Заголовок документа: ...», «Категория: ...», «Целевая аудитория: ...», «Версия: ...», «Автор: ...», «Био: ...», «Email: ...», «Текст CTA: ...», «Источник документа: ...».

## ЖЁСТКИЕ ТРЕБОВАНИЯ К СТРУКТУРЕ

Whitepaper ДОЛЖЕН содержать:
- H1 заголовок исследования
- Короткий лид без клише (без «в этом отчёте», «как известно», «стоит отметить»)
- Блок `## Executive Summary` — 300-600 слов, сжатый обзор проблемы и главных выводов
- От 6 до 12 H2-разделов основного исследования
- Блок `## Ключевые выводы` — минимум 5 пронумерованных выводов, каждый вывод 1-3 предложения с конкретикой (не просто заголовки-фразы)
- Блок `## Рекомендации` — минимум 5 пронумерованных рекомендаций, каждая с обоснованием и действием
- От 6 до 11 markdown-ссылок в теле

Проверь перед выдачей:
1. Есть `## Executive Summary` объёмом 300-600 слов?
2. Под `## Ключевые выводы` есть 5+ пронумерованных пунктов с содержимым, а не только заголовок?
3. Под `## Рекомендации` есть 5+ пронумерованных пунктов с обоснованием?
4. Всего H2 от 6 до 12?
5. Общий объём 4000-7000 слов?
6. Первый абзац без клише «в этом отчёте», «как известно», «стоит отметить», «нельзя не отметить»?
7. В теле НЕТ строк «Заголовок документа:», «Категория:», «Целевая аудитория:», «Автор:», «Био:», «Email:», «Версия:», «Текст CTA:», «Источник документа:»?
8. Все упомянутые модели, бренды, марки присутствуют в исходной статье (ничего не выдумано)?

Если хоть один пункт нет — исправь ДО выдачи.


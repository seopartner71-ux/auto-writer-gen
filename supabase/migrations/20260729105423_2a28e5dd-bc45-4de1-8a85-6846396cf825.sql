-- 2) Whitepaper: добавляем min_words в проверки «Ключевые выводы» и «Рекомендации», добавляем no_metadata_leak.
UPDATE document_types
SET post_checks_config = (
  SELECT jsonb_agg(
    CASE
      WHEN c->>'type' = 'key_findings_present' AND NOT (c ? 'min_words')
        THEN c || '{"min_words": 120}'::jsonb
      WHEN c->>'type' = 'recommendations_present' AND NOT (c ? 'min_words')
        THEN c || '{"min_words": 120}'::jsonb
      ELSE c
    END
  )
  FROM jsonb_array_elements(post_checks_config) AS c
) || '[{"type": "no_metadata_leak"}]'::jsonb
WHERE slug = 'whitepaper'
  AND jsonb_typeof(post_checks_config) = 'array'
  AND NOT post_checks_config @> '[{"type": "no_metadata_leak"}]';

-- 3) Добавляем no_metadata_leak в остальные array-конфиги (кроме уже обновлённого whitepaper и checklist, у которого post_checks_config — объект).
UPDATE document_types
SET post_checks_config = post_checks_config || '[{"type": "no_metadata_leak"}]'::jsonb
WHERE slug IN ('memo', 'howto', 'expert_pdf', 'faq', 'case', 'catalog')
  AND jsonb_typeof(post_checks_config) = 'array'
  AND NOT post_checks_config @> '[{"type": "no_metadata_leak"}]';

